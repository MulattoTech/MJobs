"""Browser-only v5 Mission Control verification. Does not launch an AI CLI."""
from playwright.sync_api import sync_playwright
from pathlib import Path
import argparse

parser=argparse.ArgumentParser(description="Browser-only, zero-model Mission Control acceptance")
parser.add_argument("--url",default="http://127.0.0.1:18738/")
args=parser.parse_args()
URL=args.url.rstrip("/")+"/"
out=Path.home()/"AppData"/"Local"/"Temp"/"mjobs_mission_control_visible_launch_ui.png"
with sync_playwright() as pw:
    browser=pw.chromium.launch(headless=True)
    page=browser.new_page(viewport={"width":1680,"height":980})
    errors=[];starts=[];previews=[]
    page.on("pageerror",lambda err:errors.append(str(err)))
    page.on("request",lambda req: starts.append(req.url) if req.url.endswith("/launch") else None)
    page.on("response",lambda res: previews.append(res.status) if res.url.endswith("/preview") else None)
    page.goto(URL,wait_until="domcontentloaded",timeout=23000)
    codex=page.locator('.launch-card[data-slot="codex"]')
    codex.wait_for(timeout=45000)
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('CODEX SUBAGENT POLICY')""",timeout=40000)
    print("LANES",page.locator(".launch-card").count())
    print("MAX_DEFAULT",codex.locator(".launch-max-subagents").input_value())
    print("INTENDED_DEFAULT",codex.locator(".launch-intended-subagents").input_value())
    print("VISIBLE_DEFAULT",codex.locator(".launch-mode").input_value())
    print("NON_CODEX_CONTROLS_HIDDEN",page.locator('.launch-card[data-slot="claude"] .launch-codex-capacity').is_hidden())
    print("START_LOCKED",codex.locator(".launch-start").is_disabled())
    codex.locator(".launch-preview").click()
    dialog=page.locator("#launchReviewDialog")
    dialog.wait_for(state="visible",timeout=13000)
    page.wait_for_function("""() => document.querySelector('#launchReviewText')?.textContent?.includes('CODEX SUBAGENT POLICY')""",timeout=15000)
    print("CAPACITY_IN_PROMPT", "hard maximum 50" in page.locator("#launchReviewText").inner_text())
    print("INTENDED_IN_PROMPT", "intended active target 8" in page.locator("#launchReviewText").inner_text())
    page.wait_for_function("""() => document.querySelector('#launchReviewCommand')?.textContent?.includes('agents.max_concurrent_threads_per_session=50')""",timeout=14000)
    assert "agents.max_concurrent_threads_per_session=50" in page.locator("#launchReviewCommand").text_content()
    assert "<approved prompt via stdin>" in page.locator("#launchReviewCommand").text_content()
    print("OVERRIDE_IN_COMMAND", True)
    print("APPROVED_TEXT_INPUT", True)
    print("REVIEW_MODE", "VISIBLE TERMINAL" in page.locator("#launchReviewMetadata").inner_text())
    page.locator("#launchReviewDone").click()
    dialog.wait_for(state="hidden",timeout=8000)

    max_input=codex.locator(".launch-max-subagents")
    target=codex.locator(".launch-intended-subagents")
    max_input.fill("16")
    target.fill("12")
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('hard maximum 16')""",timeout=18000)
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('intended active target 12')""",timeout=15000)
    print("CAPACITY_CHANGED",max_input.input_value(),target.input_value())
    codex.locator(".launch-preview").click()
    dialog.wait_for(state="visible",timeout=8000)
    page.wait_for_function("""() => document.querySelector('#launchReviewCommand')?.textContent?.includes('max_concurrent_threads_per_session=16')""",timeout=14000)
    print("CONFIG_REVIEW_CONSISTENT",True)
    page.locator("#launchReviewApprove").click()
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-start').disabled===false""",timeout=15000)
    print("APPROVAL_UNLOCKED",True)
    codex.locator(".launch-mode").select_option("headless")
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('launch_mode=headless')""",timeout=14000)
    print("MODE_CHANGE_RELOCKED",codex.locator(".launch-start").is_disabled())
    target.fill("0")
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('intended active target 0')""",timeout=15000)
    codex.locator(".launch-preview").click()
    dialog.wait_for(state="visible",timeout=7000)
    page.wait_for_function("""() => document.querySelector('#launchReviewCommand')?.textContent?.includes('features.multi_agent=false')""",timeout=14000)
    print("ZERO_TARGET_HARD_DISABLE",True)
    print("HEADLESS_REVIEW", "HEADLESS" in page.locator("#launchReviewMetadata").inner_text())
    page.locator("#launchReviewDone").click()
    dialog.wait_for(state="hidden",timeout=7000)

    # Restore reviewed choices in the browser only; no settings are committed on server.
    codex.locator(".launch-mode").select_option("terminal")
    max_input.fill("50")
    target.fill("20")
    page.wait_for_function("""() => document.querySelector('[data-slot="codex"] .launch-prompt-preview')?.textContent?.includes('intended active target 20')""",timeout=15000)
    print("SELECTED_20_OF_50",True)
    page.screenshot(path=str(out),full_page=True)
    print("SCREENSHOT",out,out.stat().st_size)
    print("PREVIEW_RESPONSES",len(previews),"FAILURES",sum(x!=200 for x in previews))
    print("LAUNCH_NETWORK_REQUESTS",starts)
    print("JS_ERRORS",errors)
    assert not starts and not errors
    assert len(previews)>0 and all(x==200 for x in previews)
    browser.close()
