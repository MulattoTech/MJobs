'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {MasterControls}=require('./master-controls');
const {RestoreFleet}=require('./restore-fleet');
const {shouldKill,watchdogVerified}=require('./quota-guard');
const base=fs.mkdtempSync(path.join(require('node:os').tmpdir(),'ao-7pct-regression-'));
(async()=>{
 const engine=()=>({config:{enabled:false},enable(x){this.config.enabled=x}});
 const m=new MasterControls({root:base,sustain:engine(),turbo:engine(),command:async()=>'',audit:()=>{},getState:async()=>({sessions:[]}),getAllSessions:async()=>[],autoschedule:false});
 let disarmed=0;let began=false;
 m.quota={status:()=>({fresh:true,selectedRemainingPercent:93,config:{autoKillArmed:true,thresholdPercent:7}}),disarm:()=>{disarmed++}};
 m.restore.getSnapshot=()=>({sessions:[{}],restorableCount:1});
 m.restore.preview=async()=>({totalTargets:1,alreadyOnline:0,willResume:1,emergencyLatched:false});
 m.restore.start=()=>{began=true;return {total:1}};
 await m.restoreStart({autoDispatchAfter:false});
 assert.equal(disarmed,0,'Restore must not remove the armed 7% guard');assert.equal(began,true);
 began=false;m.quota.status=()=>({fresh:true,selectedRemainingPercent:7,config:{autoKillArmed:true,thresholdPercent:7}});
 await assert.rejects(()=>m.restoreStart(),/threshold/);assert.equal(began,false);
 m.quota.status=()=>({fresh:false,selectedRemainingPercent:null,config:{autoKillArmed:true,thresholdPercent:7}});
 await assert.rejects(()=>m.restoreStart(),/stale/);
 m.quota.status=()=>({fresh:true,selectedRemainingPercent:90,config:{autoKillArmed:false,tripped:true,thresholdPercent:7}});
 await assert.rejects(()=>m.restoreStart(),/re-armed/);
 assert.equal(began,false,'A tripped 7% guard must block restore even with a high recorded remaining value');
 m.quota.status=()=>({fresh:true,selectedRemainingPercent:90,config:{autoKillArmed:true,tripped:false,thresholdPercent:7}});
 m.latch={enabled:true};
 fs.writeFileSync(path.join(base,'emergency-latch.json'),JSON.stringify(m.latch));
 await assert.rejects(()=>m.restoreStart(),/latched/);
 assert.equal(began,false,'Emergency latch must not be silently released by Restore Fleet');
 m.rearm();
 let commands=0;
 const root={id:'root-1',projectId:'p',kind:'orchestrator',harness:'codex',activity:{state:'exited'},isTerminated:false};
 const worker={...root,id:'worker-1',kind:'worker'};
 const r=new RestoreFleet({root:base,autoSchedule:false,locked:()=>false,audit:()=>{},getGlobalSessions:async()=>[root,worker],runtimeInspector:async()=>new Map([['root-1',0],['worker-1',0]]),command:async()=>{commands++},resourceReader:async()=>({ramGiB:20,diskGiB:100,cpuPercent:10})});
 r.state.active=true;r.state.source={targets:[root,worker]};r.state.errors={'root-1':{attempts:3}};
 const blocked=await r.tick();assert.deepEqual(blocked.blockedRoots,['root-1']);assert.equal(commands,0,'Workers must not start without a healthy primary');
 const c={enabled:true,autoKillArmed:true,tripped:false,thresholdPercent:7};
 assert.equal(shouldKill(c,8),false);assert.equal(shouldKill(c,7),true);assert.equal(shouldKill(c,6),true);assert.equal(shouldKill(c,null),false);
 const now=Date.now();
 assert.equal(watchdogVerified({active:true,phase:'holding_zero',checkedAt:new Date(now-5000).toISOString()},now),true);
 assert.equal(watchdogVerified({active:true,phase:'partial_stop',checkedAt:new Date(now-5000).toISOString()},now),true);
 assert.equal(watchdogVerified({active:true,phase:'starting',checkedAt:new Date(now-5000).toISOString()},now),false);
 assert.equal(watchdogVerified({active:true,phase:'holding_zero',checkedAt:new Date(now-60000).toISOString()},now),false);
 console.log('PASS: 7% restore gated; watchdog stale heartbeat rejected; threshold 8/7/6 correct; no production shutdown executed.');
})().catch(e=>{console.error(e);process.exitCode=1}).finally(()=>fs.rmSync(base,{recursive:true,force:true}));
