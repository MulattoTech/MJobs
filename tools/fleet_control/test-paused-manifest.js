'use strict';
const fs=require('node:fs'),path=require('node:path'),assert=require('node:assert/strict');
const {RestoreFleet}=require('./restore-fleet');
const root=path.join(__dirname,'test-paused-manifest');
fs.rmSync(root,{force:true,recursive:true});fs.mkdirSync(root,{recursive:true});
const desired=Array.from({length:29},(_,i)=>'project-'+(i+1));
const snapshot={at:'2026-10-23T08:05:13Z',sessions:desired.map(id=>({id,projectId:'project',harness:'codex',kind:'worker',isTerminated:false,activity:'idle'})),restorableCount:29};
fs.writeFileSync(path.join(root,'restore-snapshot.json'),JSON.stringify(snapshot));
fs.writeFileSync(path.join(root,'restore-state.json'),JSON.stringify({active:false,phase:'paused',desiredIds:desired}));
const r=new RestoreFleet({root,autoSchedule:false,locked:()=>false,getGlobalSessions:async()=>[{id:'other-1',projectId:'other',harness:'codex',kind:'orchestrator',isTerminated:false,activity:{state:'idle'}}],audit:()=>{},resourceReader:async()=>({ramGiB:25,diskGiB:50,cpuPercent:5})});
(async()=>{
 assert.equal(await r.captureSnapshot(),null,'paused recovery should never overwrite its manifest');
 assert.equal(r.getSnapshot().restorableCount,29);
 assert.equal(r.getSnapshot().at,snapshot.at);
 r.state.phase='complete';
 const done=await r.captureSnapshot();
 assert.equal(done.restorableCount,1,'after completed recovery snapshots may refresh');
 fs.rmSync(root,{force:true,recursive:true});
 console.log('PASS snapshot guard: paused 29-agent manifest remains intact despite a 1-agent live enumeration');
})().catch(e=>{console.error(e);process.exitCode=1;fs.rmSync(root,{force:true,recursive:true})});
