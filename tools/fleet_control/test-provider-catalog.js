'use strict';
const assert=require('node:assert/strict'),{discoverProviderCatalog,validateSelection,buildProviderArgs}=require('./provider-catalog');
const c=discoverProviderCatalog({codexModels:[{id:'gpt-6-luna',name:'Luna'}],codexEfforts:['low','medium','high','xhigh'],agyAvailable:true,agyVersion:'1.4.7',agyModelIds:['gemini-3.8-flash-high','gemini-3.8-flash-low','claude-sonnet-4-6','unverified-model'],geminiAvailable:false});
assert.equal(c.providers.find(p=>p.id==='agy').models.length,3);
assert.equal(c.providers.find(p=>p.id==='gemini').available,false);
const high={harness:'agy',model:'gemini-3.8-flash-high',effort:'high',mode:'tui'};
assert.equal(validateSelection(high,c).launchEffort,null);
assert.deepEqual(buildProviderArgs(high,c),['--harness','agy','--model','gemini-3.8-flash-high']);
assert.throws(()=>validateSelection({...high,effort:'xhigh'},c),/not supported/);
assert.throws(()=>validateSelection({...high,model:'unverified-model'},c),/verified/);
assert.throws(()=>validateSelection({...high,harness:'gemini'},c),/not found/);
assert.throws(()=>validateSelection({...high,mode:'terminal'},c),/Mode/);
assert.deepEqual(buildProviderArgs({harness:'codex',model:'gpt-6-luna',effort:'high'},c),['--harness','codex','--model','gpt-6-luna','--effort','high']);
assert.throws(()=>validateSelection({harness:'agy',model:'claude-sonnet-4-6',effort:'max'},c),/not supported/);
console.log('PASS provider-specific model/effort validation, AGY native variant args, unsupported modes/providers fail closed');
