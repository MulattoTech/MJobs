'use strict';
const assert=require('node:assert/strict'),fs=require('node:fs'),os=require('node:os'),path=require('node:path');
const {AgentPlans}=require('./agent-plans'),{preflight}=require('./preflight');
const root=fs.mkdtempSync(path.join(os.tmpdir(),'fleet-plans-test-'));
const plans=new AgentPlans({root,validate:async x=>{if(x.model!=='test')throw Error('Invalid model');return {harness:'codex',model:x.model,effort:'medium',mode:'tui'}}});
(async()=>{
 const s={id:'worker-1',kind:'worker',activity:'exited'};
 const v=await plans.save(s,{model:'test'});assert.equal(v.plan.status,'pending');
 assert.equal(plans.all().plans.length,1);
 await assert.rejects(()=>plans.save(s,{model:'bad'}),/Invalid model/);
 const p=plans.begin(s.id);assert.throws(()=>plans.begin(s.id),/No pending/);
 plans.finish(s.id,p.planId,'unverified');
 await assert.rejects(()=>plans.save(s,{model:'test'}),/unverified/);
 await assert.rejects(()=>plans.save({...s,kind:'orchestrator'},{model:'test'}),/controlled handoff/);
 const q={fresh:true,selectedRemainingPercent:0,config:{thresholdPercent:7,autoKillArmed:false,tripped:true}};
 const report=preflight({quota:q,master:{emergency:{latched:true,remainingTotal:0,checkedAt:new Date().toISOString()},dispatch:{sustainedEnabled:false}},snapshot:{offline:true}});
 assert.equal(report.ready,false);assert.equal(report.canSaveAgentPlans,true);
 assert.equal(report.issues.length,4);assert.equal(report.quota.brakeAt,15);
 console.log('PASS: settings can be staged without launch; invalid choices rejected; unverified apply cannot be retried; preflight cannot show ready at zero quota.');
 fs.rmSync(root,{recursive:true,force:true});
})().catch(e=>{console.error(e);process.exitCode=1});
