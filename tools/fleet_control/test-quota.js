'use strict';
const assert=require('node:assert/strict');
const fs=require('node:fs');
const path=require('node:path');
const {inspectLimits,selectedWindows,shouldKill,sane,configRevision}=require('./quota-guard');
const {QuotaControl}=require('./quota-control');
const root=path.join(__dirname,'test-quota-state');
fs.rmSync(root,{recursive:true,force:true});fs.mkdirSync(root,{recursive:true});
let fakeSpawned=0;const events=[];
const ctrl=new QuotaControl({root,autoSchedule:false,spawnMonitor:()=>++fakeSpawned,audit:(evt,detail)=>events.push({evt,detail})});
function sample(){
 const reset=Math.floor(Date.now()/1000)+3600;
 return {rateLimitsByLimitId:{codex:{limitId:'codex',primary:{usedPercent:67,windowDurationMins:10080,resetsAt:reset},secondary:{usedPercent:92,windowDurationMins:300,resetsAt:reset}},other:{primary:{usedPercent:99,windowDurationMins:30}}}};
}
const rows=inspectLimits(sample());
assert.equal(rows.length,2);
assert.deepEqual(rows.map(r=>r.remainingPercent),[33,8]);
assert.equal(selectedWindows(rows,'weekly')[0].remainingPercent,33);
assert.equal(selectedWindows(rows,'five-hour')[0].remainingPercent,8);
assert.equal(selectedWindows(rows,'any').length,2);
assert.equal(shouldKill({enabled:true,autoKillArmed:true,tripped:false,thresholdPercent:10},8),true);
assert.equal(shouldKill({enabled:true,autoKillArmed:false,tripped:false,thresholdPercent:10},8),false);
assert.equal(shouldKill({enabled:true,autoKillArmed:true,tripped:true,thresholdPercent:10},8),false);
assert.equal(shouldKill({enabled:true,autoKillArmed:true,tripped:false,thresholdPercent:5},8),false);
assert.equal(shouldKill({enabled:true,autoKillArmed:true,tripped:false,thresholdPercent:8},8),true);
assert.equal(shouldKill({enabled:true,autoKillArmed:true,tripped:false,thresholdPercent:20},null),false);
assert.equal(sane({thresholdPercent:70}).thresholdPercent,7);
assert.equal(sane({pollSeconds:0}).pollSeconds,5);
assert.throws(()=>ctrl.update({thresholdPercent:80}),/threshold/);
assert.throws(()=>ctrl.update({window:'unknown'}),/window/);
const original=ctrl.status();
assert.equal(original.config.autoKillArmed,false);
assert.equal(original.fresh,false);
assert.throws(()=>ctrl.arm(),/fresh/);
const statusFile=path.join(root,'quota-guard-status.json');
const data={status:'fresh',windows:rows,lastSuccessfulPoll:new Date().toISOString(),heartbeatAt:new Date().toISOString(),error:null};
fs.writeFileSync(statusFile,JSON.stringify(data));
const current=ctrl.status();
assert.equal(current.fresh,true);
assert.equal(current.selectedRemainingPercent,8);
const lockedSample={...data,status:'emergency_locked',windows:rows.map(r=>({...r,usedPercent:100,remainingPercent:0}))};
fs.writeFileSync(statusFile,JSON.stringify(lockedSample));
const lockedStatus=ctrl.status();
assert.equal(lockedStatus.fresh,true,'Emergency lock keeps read-only usage fresh');
assert.equal(lockedStatus.selectedRemainingPercent,0);
assert.match(ctrl.dispatchBlockReason(),/not armed/,'Live usage must never lift the guard');
fs.writeFileSync(statusFile,JSON.stringify({...lockedSample,lastSuccessfulPoll:new Date(Date.now()-120000).toISOString()}));
assert.equal(ctrl.status().fresh,false,'Old emergency readings must not be labeled live');
fs.writeFileSync(statusFile,JSON.stringify(data));
ctrl.update({thresholdPercent:6,window:'weekly'});
assert.equal(ctrl.status().config.window,'weekly');
assert.equal(ctrl.status().selectedRemainingPercent,33);
const enabled=ctrl.arm();
assert.equal(enabled.config.autoKillArmed,true);
assert.match(ctrl.dispatchBlockReason(),/acknowledgment/);
data.guardAck={revision:configRevision(ctrl.config()),appliedAt:data.lastSuccessfulPoll};
fs.writeFileSync(statusFile,JSON.stringify(data));
assert.equal(ctrl.dispatchBlockReason(),null);
const nearCutoff={...data,windows:rows.map(r=>({...r,remainingPercent:r.label==='Weekly'?12:r.remainingPercent}))};
fs.writeFileSync(statusFile,JSON.stringify(nearCutoff));
assert.match(ctrl.dispatchBlockReason(),/safety brake/,'new sends should pause before hard emergency cutoff');
fs.writeFileSync(statusFile,JSON.stringify(data));
ctrl.update({pollSeconds:5});
assert.equal(ctrl.status().config.autoKillArmed,true);
ctrl.update({thresholdPercent:10});
assert.equal(ctrl.status().config.autoKillArmed,false);
ctrl.arm();
ctrl.disarm();
assert.equal(ctrl.status().config.autoKillArmed,false);
assert.match(ctrl.dispatchBlockReason(),/not armed/,'an unprotected restart must fail closed');
const reboot=new QuotaControl({root,autoSchedule:false,spawnMonitor:()=>++fakeSpawned,audit:()=>{}});
assert.equal(reboot.status().config.thresholdPercent,10);
assert.equal(reboot.status().config.window,'weekly');
assert.ok(events.some(x=>x.evt==='quota_auto_stop_armed'));
assert.ok(events.some(x=>x.evt==='quota_auto_stop_disarmed'));
fs.rmSync(root,{recursive:true,force:true});
console.log('PASS quota test: real schema parsing, 5-hour/weekly selection, exact threshold, no stale triggering, arm/disarm, configuration persistence (no emergency executed)');
