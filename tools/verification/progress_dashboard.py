"""Deterministic dashboard, explicitly refreshed by the integration owner at checkpoints."""
from __future__ import annotations

import argparse
from collections import Counter, defaultdict
import json
import os
from pathlib import Path
import tempfile

ROOT = Path(__file__).resolve().parents[2]
DASHBOARD = Path("docs/PROGRESS_DASHBOARD.md")
STATUSES = ("PASS", "PARTIAL", "NOT_RUN")
PRIORITIES = ("P0", "P1", "P2", "P3", "P4", "P5", "P6")
TICK = chr(96)


def _load(path: Path) -> dict:
    result = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(result, dict):
        raise ValueError(f"Expected object: {path}")
    return result


def _count(values) -> Counter:
    counted = Counter(values)
    unknown = set(counted) - set(STATUSES)
    if unknown:
        raise ValueError(f"Unexpected acceptance status: {sorted(unknown)}")
    return counted


def _checked_counts(mapping: dict, ids: set, label: str) -> Counter:
    if set(mapping) != ids:
        missing, extra = sorted(ids - set(mapping)), sorted(set(mapping) - ids)
        raise ValueError(f"{label} ID mismatch: missing={missing[:10]}, extra={extra[:10]}")
    return _count(mapping.values())


def snapshot(root: Path = ROOT) -> dict:
    """Read-only canonical snapshot. Never infer PASS from commits or documentation."""
    root = Path(root)
    matrix = _load(root / "planning/CAPABILITY_MATRIX.json")
    reference = _load(root / "planning/REFERENCE_GAP_MATRIX.json")
    state = _load(root / "planning/IMPLEMENTATION_STATE.json")
    seeds = [
        json.loads(line)
        for line in (root / "planning/ISSUE_SEED.jsonl").read_text(encoding="utf-8").splitlines()
        if line.strip()
    ]
    seed_ids = [entry["id"] for entry in seeds]
    original_ids = [entry["requirement_id"] for entry in matrix["requirements"]]
    if len(seed_ids) != len(set(seed_ids)) or len(original_ids) != len(set(original_ids)):
        raise ValueError("Duplicate MJ-REQ identifier")
    original_map = {entry["requirement_id"]: entry["result"] for entry in matrix["requirements"]}
    original_counts = _checked_counts(original_map, set(seed_ids), "MJ-REQ")
    if reference.get("original_catalogue_count") != len(seed_ids):
        raise ValueError("MJ-REQ count disagrees with reference matrix")

    refs = reference["canonical_ids"]
    if len(refs) != len(set(refs)) or reference.get("reference_gap_count") != len(refs):
        raise ValueError("Duplicate or mismatched MJ-REF count")
    ref_map = {
        key: (value.get("result") if isinstance(value, dict) else value)
        for key, value in reference["result_by_id"].items()
    }
    ref_counts = _checked_counts(ref_map, set(refs), "MJ-REF")

    areas, priorities = defaultdict(Counter), defaultdict(Counter)
    for seed in seeds:
        result = original_map[seed["id"]]
        areas[seed["domain"]][result] += 1
        priorities[seed["priority"]][result] += 1
    release = state.get("release_readiness")
    release_result = release.get("result", "UNKNOWN") if isinstance(release, dict) else "UNKNOWN"
    return {
        "original": original_counts,
        "reference": ref_counts,
        "areas": areas,
        "priorities": priorities,
        "original_total": len(seed_ids),
        "reference_total": len(refs),
        "original_as_of": str(matrix.get("timestamp", "UNKNOWN")),
        "reference_as_of": str(reference.get("generated_at", "UNKNOWN")),
        "release": str(release_result),
        "milestone": str(state.get("current_milestone", "UNKNOWN")),
    }


def _summary(counts: Counter, total: int) -> str:
    return (
        f"**{counts['PASS']} PASS / {counts['PARTIAL']} PARTIAL / "
        f"{counts['NOT_RUN']} NOT_RUN** ({total} total; "
        f"{counts['PASS'] / total:.1%} fully accepted)"
    )


def _bar(counts: Counter, total: int) -> str:
    size = 16
    passed = round(size * counts["PASS"] / total)
    partial = min(size - passed, round(size * counts["PARTIAL"] / total))
    return "🟩" * passed + "🟨" * partial + "⬜" * (size - passed - partial)


def _rows(groups: dict, ordered=None) -> list[str]:
    names = ordered if ordered is not None else sorted(groups)
    result = []
    for name in names:
        if name not in groups:
            continue
        counts = groups[name]
        total = sum(counts.values())
        result.append(
            f"| {TICK}{name}{TICK} | {_bar(counts, total)} | {counts['PASS']} | "
            f"{counts['PARTIAL']} | {counts['NOT_RUN']} | {total} |"
        )
    return result


def render_dashboard(root: Path = ROOT) -> str:
    s = snapshot(root)
    lines = [
        "# MJobs Progress Dashboard",
        "",
        "> AUTOGENERATED from canonical matrices. Do not hand-edit counts or copy historical totals.",
        "> Only the integration owner refreshes this at accepted batches/session closeout. See [tracker policy](PROGRESS_TRACKING.md).",
        "",
        f"Original requirements: {_summary(s['original'], s['original_total'])}.",
        f"Additional reference gaps: {_summary(s['reference'], s['reference_total'])}.",
        f"Full-spec release readiness: **{s['release']}** (separate from local slice tests).",
        "",
        f"Original matrix as of: {TICK}{s['original_as_of']}{TICK}. "
        f"Reference matrix as of: {TICK}{s['reference_as_of']}{TICK}.",
        f"Latest recorded implementation milestone: {TICK}{s['milestone']}{TICK}.",
        "",
        "PASS requires evidence for the whole acceptance contract of that ID. PARTIAL is not a percentage. NOT_RUN does not necessarily mean no code exists. Local PASS is not hosted CI or full release acceptance.",
        "",
        "## Original specification by area",
        "",
        "| Area | Status chart | PASS | PARTIAL | NOT_RUN | Total |",
        "|---|---|---:|---:|---:|---:|",
    ]
    lines.extend(_rows(s["areas"]))
    lines.extend([
        "",
        "## Original specification by priority",
        "",
        "| Priority | Status chart | PASS | PARTIAL | NOT_RUN | Total |",
        "|---|---|---:|---:|---:|---:|",
    ])
    lines.extend(_rows(s["priorities"], PRIORITIES))
    lines.extend([
        "",
        "## Remaining core product work",
        "",
        "Consult the live GitHub issues, planning queue, and accepted area specs for the actual next tasks. Prioritize complete user-visible job discovery, search and matching, resume/cover-letter preparation, and supported application workflows; the dashboard does not infer issue priority.",
        "",
        "All MJ-REF supplemental requirements remain a separate denominator. Disabled hosted checks and untested live providers cannot be counted as PASS. Real external application submission stays OFF without the required user/product authorization.",
        "",
        "The dashboard has no watcher, hook, cloud dependency, timer or AI call. Detect staleness read-only using the progress_dashboard --check command; use --write only with integration ownership.",
        "",
    ])
    return "\n".join(lines)


def write_dashboard(root: Path = ROOT) -> bool:
    """Atomically update generated files at an owned acceptance checkpoint."""
    root = Path(root)
    output = root / DASHBOARD
    expected = render_dashboard(root)
    changed = not (output.is_file() and output.read_text(encoding="utf-8") == expected)
    if changed:
        output.parent.mkdir(parents=True, exist_ok=True)
        with tempfile.NamedTemporaryFile(
            mode="w", encoding="utf-8", dir=output.parent,
            prefix=".dashboard-", suffix=".tmp", delete=False, newline="\n",
        ) as handle:
            temp = Path(handle.name)
            try:
                handle.write(expected)
                handle.flush()
                os.fsync(handle.fileno())
            except BaseException:
                temp.unlink(missing_ok=True)
                raise
        try:
            os.replace(temp, output)
        finally:
            temp.unlink(missing_ok=True)
    from tools.verification.progress_card import write_card
    card_changed = write_card(root, snapshot(root))
    return changed or card_changed

def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    mode = parser.add_mutually_exclusive_group(required=True)
    mode.add_argument("--check", action="store_true")
    mode.add_argument("--write", action="store_true")
    mode.add_argument("--summary", action="store_true")
    parser.add_argument("--root", type=Path, default=ROOT)
    args = parser.parse_args(argv)
    try:
        state = snapshot(args.root)
        if args.summary:
            c = state["original"]
            r = state["reference"]
            print(f"MJ-REQ: {c['PASS']}/{state['original_total']} PASS; "
                  f"{c['PARTIAL']} PARTIAL; {c['NOT_RUN']} NOT_RUN. "
                  f"MJ-REF: {r['PASS']}/{state['reference_total']} PASS. "
                  f"Release: {state['release']}.")
            return 0
        output = args.root / DASHBOARD
        if args.check:
            from tools.verification.progress_card import card_current
            current = (output.is_file() and
                       output.read_text(encoding="utf-8") == render_dashboard(args.root) and
                       card_current(args.root, state))
            print("Progress dashboard: CURRENT" if current else "Progress dashboard: STALE")
            return 0 if current else 1
        changed = write_dashboard(args.root)
        print("Progress dashboard: UPDATED" if changed else "Progress dashboard: UNCHANGED")
        return 0
    except (OSError, KeyError, TypeError, ValueError) as error:
        parser.exit(2, f"Progress dashboard: INVALID SOURCE: {error}\n")


if __name__ == "__main__":
    raise SystemExit(main())
